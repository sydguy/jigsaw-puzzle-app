const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  console.log('Launching isolated browser');
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
  page.setDefaultTimeout(30000); page.setDefaultNavigationTimeout(120000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const out = '.cache/mobile-refinements'; fs.mkdirSync(out, { recursive: true });
  const snap = name => page.getByTestId('device-frame').screenshot({ path: `${out}/${name}.png` });
  const imagesReady = () => page.waitForFunction(() => [...document.querySelectorAll('[data-testid="device-frame"] img')].every(n => n.complete && n.naturalWidth > 0), undefined, { timeout: 60000 });
  try {
    console.log('Opening collection');
    await page.goto('http://localhost:8081/collection', { waitUntil: 'networkidle' });
    await page.getByTestId('my-collection-header').waitFor();
    console.log('Adding isolated photo fixtures');
    // Isolated test photos exercise both import sources; never touch owner's browser data.
    await page.evaluate(() => new Promise((resolve, reject) => {
      const canvas = document.createElement('canvas'); canvas.width = 1536; canvas.height = 1024;
      const c = canvas.getContext('2d'); c.fillStyle = '#345689'; c.fillRect(0, 0, 1536, 1024);
      const request = indexedDB.open('jigsaw-browser-preview');
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        const db = request.result; const tx = db.transaction('pictures', 'readwrite');
        for (const source of ['photo', 'camera']) tx.objectStore('pictures').put({ id: `test-${source}`, title: source === 'camera' ? '49c93163-b887-46cd-a838-long-camera-filename.jpg' : `My ${source} image`, source, theme: 'My Photo', addedAt: Date.UTC(2026, 9, 7), data: canvas.toDataURL('image/jpeg'), width: 1536, height: 1024 });
        tx.oncomplete = () => { db.close(); resolve(); }; tx.onerror = () => { db.close(); reject(tx.error); };
      };
    }));
    await page.reload({ waitUntil: 'networkidle' });
    console.log('Fixtures loaded');
    for (const [layout, name] of [['0', 'iphone'], ['1', 'android']]) {
      console.log(`Checking ${name}`);
      await page.getByLabel('Preview layout', { exact: true }).selectOption(layout);
      await page.getByRole('tab', { name: 'My Collection', exact: true }).click();
      await page.getByTestId('my-collection-header').waitFor();
      assert.equal(await page.getByLabel('Collection review data').count(), 0);
      const cards = page.getByTestId('my-collection-item');
      assert.equal(await cards.count(), 20, 'actual photos and theme samples share a list');
      await page.getByRole('button', { name: 'Filter by Theme: All pictures', exact: true }).click();
      assert.equal((await page.getByRole('listbox', { name: 'Filter by Theme', exact: true }).getByRole('option').first().innerText()).split('\n')[0], 'All pictures');
      await page.getByRole('option', { name: 'My Pictures', exact: true }).click();
      assert.equal(await cards.count(), 2, 'photo and camera items included');
      await cards.first().click(); await cards.first().click();
      assert.equal(await cards.first().getAttribute('aria-pressed'), 'false');
      assert(await page.getByRole('button', { name: 'Create Puzzle', exact: true }).isDisabled());
      await page.getByRole('button', { name: 'Filter by Theme: My Pictures', exact: true }).click();
      await page.getByRole('option', { name: 'All Curated Themes', exact: true }).click();
      assert.equal(await cards.count(), 18, 'curated filter excludes both personal sources');
      await page.getByRole('button', { name: 'Filter by Theme: All Curated Themes', exact: true }).click();
      await page.getByRole('option', { name: 'All pictures', exact: true }).click();
      await imagesReady();
      const faceHeight = await page.getByTestId('collection-view-face').first().evaluate(n => n.getBoundingClientRect().height);
      const dropHeight = await page.getByRole('button', { name: 'Sort by: Recently Added', exact: true }).locator('span').first().evaluate(n => n.getBoundingClientRect().height);
      assert(Math.abs(faceHeight - dropHeight) < 1, 'visible segment and dropdown heights match');
      assert.notEqual(await page.getByTestId('bottom-tab-bar').evaluate(n => getComputedStyle(n).position), 'absolute');
      assert.notEqual(await page.getByTestId('screen-footer-container').evaluate(n => getComputedStyle(n).position), 'absolute');
      assert.equal(await page.getByRole('button', { name: /Picture details:/ }).count(), 0);
      await snap(`${name}-grid`);
      await page.getByRole('button', { name: 'Detailed', exact: true }).click();
      await page.waitForFunction(() => {
        const card = document.querySelector('[data-testid="my-collection-item"]'); const img = card?.querySelector('[aria-label][style*="background-image"]') ?? card?.querySelector('img');
        if (!card || !img) return false;
        const a = card.getBoundingClientRect(), b = img.getBoundingClientRect();
        return Math.abs((b.y-a.y) - (b.x-a.x)) < 1 && Math.abs((a.bottom-b.bottom) - (b.x-a.x)) < 1;
      });
      const measured = await cards.first().evaluate(n => {
        const a = n.getBoundingClientRect(), b = (n.querySelector('[aria-label][style*="background-image"]') ?? n.querySelector('img')).getBoundingClientRect();
        return { ratio: b.width/b.height, left: b.x-a.x, top: b.y-a.y, bottom: a.bottom-b.bottom };
      });
      assert(Math.abs(measured.ratio - 1.5) < .01); assert(Math.abs(measured.top-measured.left) < 1); assert(Math.abs(measured.bottom-measured.left) < 1);
      assert(await page.getByTestId('page-scroll').evaluate(n => n.scrollWidth <= n.clientWidth), 'detailed rows stay within their scroll viewport');
      const photoSize = await cards.first().locator('img').boundingBox(), themeSize = await cards.nth(2).locator('img').boundingBox();
      assert.equal(photoSize.width, themeSize.width); assert.equal(photoSize.height, themeSize.height);
      assert.equal(await cards.first().getByText('49c93163-b887-46cd-a838-long-camera-filename.jpg', { exact: true }).evaluate(n => getComputedStyle(n).whiteSpace), 'nowrap');
      await cards.first().click(); await snap(`${name}-detailed`);
      await cards.first().click();
      assert(await page.getByRole('button', { name: 'Create Puzzle', exact: true }).isDisabled());
      const footer = await page.getByTestId('my-collection-footer').boundingBox();
      await page.getByRole('scrollbar').focus(); await page.keyboard.press('End');
      await page.waitForFunction(() => document.querySelector('[data-testid="page-scroll"]')?.scrollTop > 0);
      const last = await cards.last().boundingBox(); assert(last.y + last.height < footer.y, 'last card fully visible above fixed actions');
      await snap(`${name}-scrolled`);
      await page.getByTestId('page-scroll').evaluate(n => { n.scrollTop = 0; });
      const row = page.getByTestId('swipe-delete-row').first();
      const bounds = await row.boundingBox();
      await page.mouse.move(bounds.x + bounds.width - 25, bounds.y + bounds.height / 2); await page.mouse.down();
      await page.mouse.move(bounds.x + bounds.width - 130, bounds.y + bounds.height / 2, { steps: 12 }); await page.mouse.up();
      const deleteAction = row.getByRole('button', { name: /^Delete / });
      await deleteAction.waitFor({ state: 'visible' });
      assert.equal(await deleteAction.evaluate(n => getComputedStyle(n).backgroundColor), 'rgb(245, 34, 53)');
      assert.equal(await deleteAction.getByTestId('card-delete-icon').count(), 1);
      await snap(`${name}-swipe`);
      await deleteAction.click();
      const dialog = page.getByRole('dialog');
      assert(await dialog.getByRole('button', { name: 'Cancel', exact: true }).evaluate(n => n === document.activeElement));
      await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
      assert.equal(await cards.count(), 20, 'cancelling preserves the picture');
      await row.focus(); await page.keyboard.press('ArrowRight');
      const sampleRow = page.getByTestId('swipe-delete-row').nth(2);
      await sampleRow.focus(); await page.keyboard.press('ArrowLeft');
      await sampleRow.getByRole('button', { name: /^Delete / }).click();
      await dialog.getByRole('button', { name: 'Delete picture', exact: true }).click();
      await page.waitForFunction(() => document.querySelectorAll('[data-testid="my-collection-item"]').length === 19);
      await page.getByRole('tab', { name: 'Settings', exact: true }).click();
      await page.getByRole('button', { name: 'Sign In', exact: true }).click();
      await page.getByRole('status').filter({ hasText: 'Sign-in services are not connected' }).waitFor();
      const preferences = await page.getByTestId('settings-play-preferences').boundingBox(), signIn = await page.getByRole('button', { name: 'Sign In', exact: true }).boundingBox();
      assert(signIn.y >= preferences.y + preferences.height, 'Sign In below preferences');
      await page.getByRole('button', { name: 'Sign Up', exact: true }).click();
      await page.getByRole('status').filter({ hasText: 'Sign-up services are not connected' }).waitFor();
      assert(await page.getByTestId('page-scroll').evaluate(n => n.scrollHeight <= n.clientHeight + 1), 'guest Settings fits without scrolling');
      await imagesReady(); await snap(`${name}-guest`);
      await page.getByLabel('Settings account review').selectOption('signed-in');
      await page.getByRole('heading', { name: 'Sarah Johnson', exact: true }).waitFor();
      assert(await page.getByTestId('page-scroll').evaluate(n => n.scrollHeight <= n.clientHeight + 1), 'signed-in Settings fits without scrolling');
      await page.getByRole('button', { name: 'Sign Out', exact: true }).scrollIntoViewIfNeeded();
      await snap(`${name}-signed-in`);
      await page.getByRole('button', { name: 'Sign Out', exact: true }).click();
      await page.getByRole('button', { name: 'Sign In', exact: true }).waitFor();
    }
    await page.getByRole('tab', { name: 'My Collection', exact: true }).click();
    await page.getByRole('button', { name: 'Detailed', exact: true }).click();
    const real = page.getByTestId('swipe-delete-row').first();
    await real.focus(); await page.keyboard.press('ArrowLeft');
    await real.getByRole('button', { name: /^Delete / }).click();
    await page.evaluate(() => { window.originalDelete = IDBObjectStore.prototype.delete; IDBObjectStore.prototype.delete = function() { throw new Error('Injected storage failure'); }; });
    await page.getByRole('dialog').getByRole('button', { name: 'Delete picture', exact: true }).click();
    await page.getByRole('dialog').getByRole('alert').waitFor();
    assert.equal(await page.getByTestId('my-collection-item').count(), 20, 'failed deletion preserves rows');
    await page.evaluate(() => { IDBObjectStore.prototype.delete = window.originalDelete; });
    await page.getByRole('dialog').getByRole('button', { name: 'Delete picture', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[data-testid="my-collection-item"]').length === 19);
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByTestId('my-collection-header').waitFor();
    assert.equal(await page.getByTestId('my-collection-item').count(), 19, 'actual deletion survives reload');
    await page.getByRole('tab', { name: 'Home', exact: true }).click();
    await page.getByLabel('Home review state').selectOption('populated');
    await imagesReady();
    const homeRow = page.getByTestId('swipe-puzzle-row').first();
    await homeRow.focus(); await page.keyboard.press('ArrowLeft');
    assert.equal(await homeRow.getByRole('button', { name: /^Delete / }).evaluate(n => getComputedStyle(n).backgroundColor), 'rgb(245, 34, 53)');
    assert.equal(await homeRow.getByTestId('card-delete-icon').count(), 1);
    await snap('home-shared-delete');
    await homeRow.getByRole('button', { name: /^Delete / }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Delete puzzle', exact: true }).click();
    assert.equal(await page.getByTestId('swipe-puzzle-row').count(), 6);
    await page.goto('http://localhost:8081/collection-pictures?collection=nature&returnTo=create', { waitUntil: 'networkidle' });
    const sample = page.getByTestId('collection-picture-sample-1');
    await sample.click(); await sample.click();
    assert.equal(await sample.getAttribute('aria-pressed'), 'false');
    assert(await page.getByRole('button', { name: 'Add Picture', exact: true }).isDisabled());
    assert.deepEqual(errors, []);
    console.log('PASS: filters, nonfloating Collection controls, uniform single-line thumbnails, swipe/cancel/delete, storage failure recovery and persistence, shared Home deletion, compact guest/signed-in Settings and sign-up prompt on both phones.');
  } catch (error) {
    await page.screenshot({ path: `${out}/failure.png` }).catch(() => {});
    throw error;
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
